def test_seed_consistency_keeps_one_adverse_seed_visible(evidence):
    rows = report.accuracy_tables(evidence)["crossed_contrasts"]
    selected = [r for r in rows if r["group"]==rows[0]["group"] and
        r["time_index"]==0 and r["statistic"]=="mean" and r["variant"]==rows[0]["variant"]]
    assert len(selected)==3
    selected[-1]["advantage"] = -.02
    selected[-1]["lower95"],selected[-1]["upper95"] = -.03,-.01
    result = report.seed_consistency(selected)[0]
    assert not result["all_seeds_candidate_closer_pointwise95"]
    assert not result["all_seeds_control_closer_pointwise95"]
    assert result["minimum_advantage"]==-.02
    with pytest.raises(ValueError,match="drop or duplicate"):
        report.seed_consistency(selected[:-1])


def test_costs_charge_one_complete_input_build_not_four_or_twelve(evidence):
    data,workers,pools,preparations = report._data_workers(evidence)
    case = evidence["plan"]["cases"][0]
    costs,totals,study = report.cost_tables(evidence["timing"],evidence["lock"],{case:2.},
        preparation_seconds=sum(p["wall_seconds"] for p in preparations),
        pool_seconds={(case,seed):.5 for seed in (0,1,2)},worker_seconds=sum(w["wall_seconds"] for w in workers))
    assert len(data)==2 and len(pools)==3
    assert study["all_model_optimizer_loop_seconds"]==12.
    assert study["all_model_fit_invocation_seconds"]==24.
    assert study["full_prepare_plus_worker_seconds"]==63.  # NOT +24 fit, +2 native, +1.5 conversion again.
    head = next(c for c in costs if c["family"]=="repaired" and c["role"]=="conditional" and c["batch"]==1)
    assert head["known_offline_seconds"]==pytest.approx(2.+3.+.5+.2)
    ensemble = next(c for c in costs if c["name"]==head["name"] and c["role"]=="ensemble")
    assert ensemble["known_offline_seconds"]==pytest.approx(5.7+.03)
    q100 = next(r for r in totals if r["slot"]==ensemble["slot"] and r["query_calls"]==100)
    assert q100["total_known_seconds"]==pytest.approx(5.7+.03+.03+99*.001)
    evidence["lock"]["models"][0]["full_invocation_cost_complete"] = False
    with pytest.raises(ValueError,match="Full fit"):
        report.cost_tables(evidence["timing"],evidence["lock"],{case:2.})


def test_fast_model_without_accuracy_or_sampling_gate_has_no_qualified_payback(evidence):
    tables = report.accuracy_tables(evidence)
    case = evidence["plan"]["cases"][0]
    tables["costs"],_,_ = report.cost_tables(evidence["timing"],evidence["lock"],{case:2.},
        preparation_seconds=3.,pool_seconds={(case,s):.5 for s in (0,1,2)},worker_seconds=60.)
    rows = report.amortization_tables(tables)
    assert any(r["accuracy_qualified_payback_calls"] for r in rows)
    for r in tables["accuracy"]:
        if r["family"]=="repaired":
            r["max_mean_error_in_reference_std"] = .2
    for r in tables["sampling"]:
        if r["family"]=="native-MC":
            r["covariance95_radius"] = .2
    failed = report.amortization_tables(tables)
    assert all(r["accuracy_qualified_payback_calls"] is None for r in failed if r["statistic"]=="mean")
    assert all(r["accuracy_qualified_payback_calls"] is None for r in failed if r["statistic"]=="covariance" and r["control"]=="native-MC-dt10")
    assert any(r["descriptive_payback_calls"] is not None for r in failed)


def test_report_and_archive_roundtrip_bind_inputs_outputs_exact_sources(evidence,tmp_path):
    root = evidence["root"]
    manifest = report.generate(root)
    assert manifest==report.generate(root)==report.load_report(root/"report")
    result = json.loads((root/"report/report.json").read_text())
    assert result["allocation"]["models"]==12
    assert result["primary_IID_integration_independent"]
    assert not result["continuous_DK_claim"]
    text = (root/"report/report.md").read_text()
    assert "not a simultaneous" in text and "not an equal-accuracy" in text
    archive = tmp_path/"archive"
    archived = report.archive(root,archive)
    assert archived["allocation"]["total_retained_accuracy_records"]==122
    assert report.verify_archive(archive)==archived
    assert (archive/"code/analysis/report_payoff_collocation_study.py").read_bytes()==Path(report.__file__).read_bytes()
    assert not list(archive.rglob("*.npz"))
    (archive/"extra.txt").write_text("unindexed")
    with pytest.raises(ValueError,match="inventory changed"):
        report.verify_archive(archive)
    (root/"report/accuracy.csv").write_text("changed")
    with pytest.raises(ValueError,match="output evidence"):
        report.load_report(root/"report")


