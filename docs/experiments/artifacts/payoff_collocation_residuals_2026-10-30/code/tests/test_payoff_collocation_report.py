def test_literal_allocation_and_real_tables_preserve_every_seed_and_variant(evidence):
    allocation = report.validate_evidence(evidence)
    assert allocation==dict(cases=1,models=12,primary_accuracy_records=96,
        independent_initial_records=26,total_retained_accuracy_records=122,timing_records=116,restoration_records=26)
    tables = report.accuracy_tables(evidence)
    assert len(tables["accuracy"])==96*3
    assert len(tables["crossed_contrasts"])==9*6*3*2
    assert {r["variant"] for r in tables["crossed_seed_consistency"]}==set(report.VARIANTS)-{report.BASELINE}
    assert all(r["all_seeds_candidate_closer_pointwise95"] for r in tables["crossed_seed_consistency"])
    assert all(r["control"].endswith("_uniform_pseudo_huber_seed"+str(r["seed"]))
               for r in tables["crossed_contrasts"])
    assert all(r["name"].endswith("seed"+str(r["seed"])) for r in tables["crossed_contrasts"])
    assert any(r["stopped"]==1 for r in tables["stopping"])
    assert len(report.training_tables(evidence))==24


@pytest.mark.parametrize("mutation",["seed","variant","prediction","query","paired","integration",
    "paired_query","contrast","contrast_query","refinement","refinement_level","timing","timing_metadata","loading","samples","components"])
def test_partial_or_relabelled_evidence_never_counts_as_success(evidence,mutation):
    if mutation=="seed":
        evidence["lock"]["models"] = [m for m in evidence["lock"]["models"] if m["seed"]!=2]
