@pytest.mark.parametrize("missing",[True,False])
def test_compressed_archive_payload_is_required_and_lossless(evidence,tmp_path,missing):
    root = evidence["root"]
    report.generate(root)
    destination = tmp_path/"compact"
    report.archive(root,destination)
    compressed = next(destination.rglob("*.json.gz"))
    if missing:
        compressed.unlink()
    else:
        compressed.write_bytes(b"mutated compressed report")
    with pytest.raises(ValueError,match="inventory changed|Archived evidence changed"):
        report.verify_archive(destination)


